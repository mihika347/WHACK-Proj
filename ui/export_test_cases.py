"""Bundle the saved AI test cases so the UI can open directly from disk."""

import json
from pathlib import Path


def main():
    ui = Path(__file__).resolve().parent
    report = json.loads((ui.parent / "tests/correctness_cases.json").read_text(encoding="utf-8"))
    groups = {}
    for filename, result in report["targeted"].items():
        agent = result.get("agent")
        if not agent:
            continue
        cases = agent["cases"]
        key = (agent["fingerprint"], json.dumps(cases, sort_keys=True))
        if key not in groups:
            groups[key] = {
                "sources": [],
                "cases": [
                    {
                        "name": case["name"],
                        "input": f"count_matches({case['numbers']}, {case['target']})",
                        "reason": case["reason"],
                    }
                    for case in cases
                ],
            }
        groups[key]["sources"].append(filename)

    # Format inputs in Python to preserve integers larger than JavaScript can store exactly.
    data = json.dumps(list(groups.values()), indent=2)
    (ui / "agent-test-cases.js").write_text(
        f"// Generated by export_test_cases.py from the saved correctness suite.\nconst agentTestCases = {data};\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
