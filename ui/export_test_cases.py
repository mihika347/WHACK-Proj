"""Bundle saved test cases and correctness results for the local UI."""

import json
from pathlib import Path


def case_key(case):
    return case["name"], tuple(case["numbers"]), case["target"]


def display_case(case, failed_in=None):
    # Format integers in Python so large values stay exact in the browser.
    numbers = case["numbers"]
    limit = 12
    reason = case.get("reason", "")
    if len(numbers) > limit:
        shown = "[" + ", ".join(map(str, numbers[:limit])) + ", …]"
        preview = f"Showing the first {limit} of {len(numbers):,} input values."
        reason = f"{reason} {preview}".strip()
    else:
        shown = str(numbers)
    entry = {
        "name": case["name"],
        "input": f"count_matches({shown}, {case['target']})",
        "reason": reason,
    }
    if failed_in:
        entry["failedIn"] = failed_in
    return entry


def correctness_groups(suite, failures):
    def display(case):
        return display_case(case, failures.get(case_key(case)))

    targeted = {}
    groups = {}
    for filename, result in suite["targeted"].items():
        for case in result["cases"]:
            targeted[case_key(case)] = case
        agent = result.get("agent")
        if not agent:
            continue
        cases = agent["cases"]
        key = (agent["fingerprint"], json.dumps(cases, sort_keys=True))
        if key not in groups:
            groups[key] = {
                "sources": [],
                "cases": [display(case) for case in cases],
            }
        groups[key]["sources"].append(filename)

    return [
        {"sources": ["AI-generated", *group["sources"]], "cases": group["cases"]}
        for group in groups.values()
    ] + [
        {"sources": ["Shared cases"], "cases": [display(case) for case in suite["shared_cases"]]},
        {"sources": ["Targeted and exhaustive cases"], "cases": [display(case) for case in targeted.values()]},
    ]


def main():
    ui = Path(__file__).resolve().parent
    root = ui.parent
    suite = json.loads((root / "tests/correctness_cases.json").read_text(encoding="utf-8"))
    report = json.loads((root / "reports/correctness_report.json").read_text(encoding="utf-8"))
    completed = [candidate for candidate in report["candidates"] if "passed" in candidate]
    correctness_failures = {}
    for candidate in completed:
        for failure in candidate["failures"]:
            correctness_failures.setdefault(case_key(failure["case"]), []).append(candidate["file"])

    speed_report = json.loads((root / "reports/speed_report.json").read_text(encoding="utf-8"))
    speed_failures = {}
    speed_checks = 0
    for candidate in speed_report["candidates"]:
        for timing in candidate.get("timings", []):
            speed_checks += 1
            if timing["speedup"] < 1:
                speed_failures.setdefault(timing["name"], []).append(candidate["file"])
    slower = sum(map(len, speed_failures.values()))

    speed_groups = {}
    for case in json.loads((root / "tests/speed_cases.json").read_text(encoding="utf-8")):
        entry = display_case(case, speed_failures.get(case["name"]))
        speed_groups.setdefault(len(case["numbers"]), []).append(entry)

    data = json.dumps({
        "outcomes": {
            "correctness": {
                "passed": sum(candidate["passed"] for candidate in completed),
                "failed": sum(candidate["total"] - candidate["passed"] for candidate in completed),
            },
            "speed": {"passed": speed_checks - slower, "failed": slower},
        },
        "correctness": correctness_groups(suite, correctness_failures),
        "speed": [
            {"sources": [f"{size:,} input values"], "cases": cases}
            for size, cases in speed_groups.items()
        ],
    }, indent=2)
    (ui / "test-case-data.js").write_text(
        f"// Generated by export_test_cases.py from the saved test suites and correctness report.\nconst testCaseData = {data};\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
